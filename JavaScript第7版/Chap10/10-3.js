/**
 * ES6のモジュールシステム
 * ・ファイルをモジュールの単位とする
 * ・デフォルトでstrictモードになっている
 * ・type=moduleとするとESモジュールが有効になる
 * ・import,exportキーワードはファイルのトップレベルでしか使用できない → コードの静的解析が可能になる
 */


/**
 * 再エキスポート
 */
export { } from "~"  // 指定したモジュールからimportして再エキスポート 
export * from "~"    // 指定したモジュールからexportされているものを全て再エキスポート  

/**
 * 動的インポート
 * ・import演算子は、Promiseオブジェクトを返す
 */
import('~').then((data) => {
  console.log(data)
})

/**
 * import.meta
 * ・現在実行中のモジュールについてのメタデータに関するオブジェクトを参照できる
 * ・import.meta.urlで、今実行しているモジュールのパスを返してくれる
 */